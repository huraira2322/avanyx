export const IS_DEMO_MODE_FLAG = 'velcora_is_demo_session';

/**
 * Checks if the active client session is running in an explicit Demo mode.
 * Production environments strictly isolate demo seeds from live tenant databases.
 */
export function isDemoSessionActive(): boolean {
  if (typeof window === 'undefined') return false;
  try {
    return localStorage.getItem(IS_DEMO_MODE_FLAG) === 'true' || window.location.search.includes('demo=true');
  } catch {
    return false;
  }
}

export function setDemoSessionActive(active: boolean): void {
  if (typeof window === 'undefined') return;
  try {
    if (active) {
      localStorage.setItem(IS_DEMO_MODE_FLAG, 'true');
    } else {
      localStorage.removeItem(IS_DEMO_MODE_FLAG);
    }
  } catch {}
}

